/**
 * Writes src/governed-sql.js: the SQL Astrato's engine compiles for each stored question the app shows.
 *
 * The App runtime does not return the statement it ran, so the right-click "SQL" for governed
 * objects comes from an MCP dry run of the same stored question on the published layer.
 * Selections arrive at run time as extra conditions on the same statement. Re-run after any
 * layer change.
 *
 *   ASTRATO_MCP_CLIENT=<path to an MCP command-line client> node tools/governed-sql.mjs
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { EXTRACT_QUESTION } from '../src/questions.js';

const MCP = process.env.ASTRATO_MCP_CLIENT;
if (!MCP) { console.error('set ASTRATO_MCP_CLIENT'); process.exit(2); }
const LAYER = JSON.parse(readFileSync(new URL('../astrato.json', import.meta.url), 'utf8')).semanticLayerId;
// The question names are read from src/tiles.js as text (importing it needs a browser).
const tilesText = readFileSync(new URL('../src/tiles.js', import.meta.url), 'utf8');
const consts = Object.fromEntries([...tilesText.matchAll(/const (\w+) = (['"])(.+?)\2;/g)].map((m) => [m[1], m[3]]));
const questions = [...new Set([
  ...[...tilesText.matchAll(/question: (['"])(.+?)\1/g)].map((m) => m[2]),
  ...[...tilesText.matchAll(/question: ([A-Z_]+)\b/g)].map((m) => consts[m[1]]).filter(Boolean),
  EXTRACT_QUESTION,
])];

const out = {};
for (const id of questions) {
  const raw = execFileSync(process.execPath, [MCP, 'astrato_semantic_layer_execute_question', JSON.stringify({ semanticLayerId: LAYER, id, dryRun: true })], { encoding: 'utf8', maxBuffer: 16e6 });
  const parsed = JSON.parse(raw);
  const find = (node) => (node && typeof node === 'object' ? (typeof node.statement === 'string' ? node.statement : Object.values(node).map(find).find(Boolean)) : null);
  const statement = find(parsed);
  if (!statement) throw new Error(`${id}: no statement in ${raw.slice(0, 300)}`);
  out[id] = statement;
  console.log(`${id}: ${out[id].length} chars`);
}
writeFileSync(new URL('../src/governed-sql.js', import.meta.url), `/** Generated by tools/governed-sql.mjs: the SQL Astrato's engine compiles for each stored question (published layer). */\nexport const GOVERNED_SQL = ${JSON.stringify(out, null, 2)};\n`);
